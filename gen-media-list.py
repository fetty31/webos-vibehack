#!/usr/bin/env python3
"""List the images in CONFIG.backgroundDir into app/media-list.js for the background carousel.

The packaged app runs from file:// on the TV, where a folder cannot be listed at runtime,
so its contents are baked in here - install.sh runs this before packaging. The list is
shuffled, so the carousel shows the photos in a different, non-alphabetical order each run.

    python3 gen-media-list.py

Run it again whenever photos are added to or removed from the folder.
"""
import json
import os
import random
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP_DIR = os.path.join(HERE, "app")
OUTPUT = os.path.join(APP_DIR, "media-list.js")
EXTENSIONS = (".jpg", ".jpeg", ".png", ".gif", ".webp", ".bmp", ".avif")


def background_dir():
    with open(os.path.join(APP_DIR, "config.js"), encoding="utf-8") as f:
        found = re.search(r"backgroundDir\s*:\s*['\"]([^'\"]*)['\"]", f.read())
    return (found.group(1) if found else "").strip().strip("/")


def main():
    rel = background_dir()
    folder = os.path.normpath(os.path.join(APP_DIR, rel)) if rel else ""
    images = []
    if folder and os.path.isdir(folder) and os.path.commonpath([APP_DIR, folder]) == APP_DIR:
        for name in os.listdir(folder):
            if name.lower().endswith(EXTENSIONS) and os.path.isfile(os.path.join(folder, name)):
                images.append(rel.rstrip("/") + "/" + name)
    elif rel:
        print(f"warning: background folder '{rel}' is missing or outside the app folder", file=sys.stderr)
    random.shuffle(images)

    with open(OUTPUT, "w", encoding="utf-8") as f:
        f.write("// Generated by gen-media-list.py: the images in CONFIG.backgroundDir, shuffled.\n")
        f.write("window.MEDIA_LIST = " + json.dumps(images, indent=1) + ";\n")
    print(f"Background carousel: {len(images)} images from '{rel or '(no folder set)'}'.")


if __name__ == "__main__":
    main()
